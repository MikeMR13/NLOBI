import fs from 'node:fs';
import assert from 'node:assert/strict';
import {sanitizeTeamAppearance,exportTeamAppearance,importTeamAppearance} from '../src/team-appearance-phase-b.js';
const app=fs.readFileSync('src/app.js','utf8'),css=fs.readFileSync('src/styles.css','utf8');
for(const key of ['teamSeasonKey','teamSeasonMotionKey','teamSeasonDensityKey','teamSeasonDecor','teamSeasonControls','teamSeasonValidate','teamSeasonClasses'])assert.ok(app.includes('function '+key+'('),key+' missing');
for(const key of ['team_season','team_season_motion','team_season_density'])assert.ok(app.includes('data-team-setting="'+key+'"'),key+' field missing');
for(const key of ['sakura','nieve','momiji','matsuri'])assert.ok(css.includes('teamSeason-'+key),'Season CSS missing: '+key);
assert.ok(css.includes('@media(min-width:768px) and (prefers-reduced-motion:no-preference)'),'No mobile static fallback');
assert.ok(css.includes('@media(prefers-reduced-motion:reduce)'),'OS motion preference ignored');
assert.ok(css.includes('html[data-site-motion="reduce"]'),'User motion preference ignored');
assert.ok(css.includes('pointer-events:none'),'Decoration must not block taps');
assert.ok(app.includes('teamSeasonDecor(customization)'),'No public profile integration');
assert.ok(app.includes('teamSeasonDecor(p)'),'No preview integration');
assert.ok(app.includes('teamSeasonValidate(profile_settings)'),'Season not validated on save');
assert.ok(app.includes('teamSeasonControls(G)'),'Season selectors missing in Studio');
const selected={team_season:'matsuri',team_season_motion:'animated',team_season_density:'suave'};
assert.deepEqual(sanitizeTeamAppearance(selected),selected);
const imported=importTeamAppearance(exportTeamAppearance(selected,'Matsuri sin costo'));
assert.deepEqual(imported.appearance,selected);
for(const bad of [{team_season:'<img src=x>'},{team_season_motion:'spin-fast'},{team_season_density:'huge'}])assert.throws(()=>sanitizeTeamAppearance(bad),'Unsafe settings accepted');
assert.equal(sanitizeTeamAppearance({}).team_season,undefined,'Legacy themes must remain compatible');
console.log('Fase C: presets, HTML integration, accessibility and reusable theme validation OK');
