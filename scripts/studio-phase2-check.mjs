import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=f=>readFileSync(new URL('../'+f,import.meta.url),'utf8');
const app=read('src/app.js'),phase1=read('supabase/migrations/20261010222100_studio_phase1_foundations.sql'),migration=read('supabase/migrations/20261010224000_studio_phase2_classification_final_volume.sql');
new Function(app);
const expectedTranslation=['active','paused','abandoned','complete','withdrawn'];
const expectedSequel=['unspecified','awaiting','unconfirmed','announced','publishing','completed'];
const states=app.match(/const TRANSLATION_EDITORIAL_STATES=(\[[^;]+\]);/)?.[1];
const sequels=app.match(/const SEQUEL_EDITORIAL_STATES=(\[[^;]+\]);/)?.[1];
assert.ok(states&&sequels,'Both editorial classifications must exist');
assert.deepEqual(new Function('return '+states)().map(x=>x[0]),expectedTranslation);
assert.deepEqual(new Function('return '+sequels)().map(x=>x[0]),expectedSequel);
for(const pattern of [/id="newNovelType" required/,/id="newNovelStatus"/,/id="newTranslationStatus"/,/id="newSequelStatus"/,/id="projectNovelStatus"/,/id="projectSequelStatus"/,/id="saveEditorialStates"/,/finalVolumeSettings\("newVolume"\)/,/finalVolumeSettings\("editVolume"/,/readFinalVolumeForm\('newVolume'\)/,/readFinalVolumeForm\('editVolume'\)/,/studioPhase2Ready/,/id="catalogNovelType"/,/searchNovelType:'all'/])assert.match(app,pattern,'Missing novel classification, independent statuses, or final-volume control');
assert.match(app,/update_editorial_states/);
assert.match(app,/novel_type/);
assert.match(phase1,/is_final_volume boolean not null default false/i);
assert.match(phase1,/save_studio_section_atomic/);
assert.match(migration,/create or replace function public\.create_translation_project_with_metadata/i);
assert.match(migration,/security invoker/i);
assert.match(migration,/create trigger volume_final_status_update/i);
assert.match(migration,/create trigger volume_final_status_delete/i);
assert.match(migration,/restore_previous_published_final/);
assert.match(migration,/auto_status_source_volume_id/);
assert.ok(!migration.includes("'awaiting_sequel'"),'Continuation belongs only to sequel_status, not translation status');
assert.ok(!migration.includes("'no_sequel_confirmed'"),'Sequel uncertainty is independent of translation status');
console.log('Studio phase 2 verified: novel type, three independent states and final-volume sync.');
